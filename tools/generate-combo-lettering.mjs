import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";

// The parser and font are build-time inputs only. Product code contains three
// fixed word outlines; it has no font loading, text shaping or path parsing.
const root = resolve(import.meta.dirname, "..");
const base = "art-source/ui/combo-praise-lettering";
const fontPath = `${base}/LilitaOne-Regular.ttf`;
const parserPath = `${base}/tooling/opentype-1.3.4.cjs`;
const outputPath = "src/game/comboPraiseLettering.ts";
const provenancePath = `${base}/provenance.json`;
const expectedFontSha256 = "f5b641c45c69d772ee4eda687bc9fda411d5cad6b0b45371491da4580cbc8d59";
const expectedParserSha256 = "aca3813e716a07e06c2e32c736d841508b15451cf39483f289acbd879c64d09f";
const targets = [
  { tier: "good", text: "Good!", width: 133, height: 34 },
  { tier: "great", text: "Great!", width: 141, height: 34 },
  { tier: "excellent", text: "Excellent!", width: 221, height: 34 },
];
const sha256 = (data) => createHash("sha256").update(data).digest("hex");
const files = [fontPath, `${base}/OFL.txt`, `${base}/FONTLOG.txt`, parserPath, `${base}/tooling/LICENSE.txt`, "tools/generate-combo-lettering.mjs"];
const sourceBindings = Object.fromEntries(await Promise.all(files.map(async (path) => [path, sha256(await readFile(resolve(root, path)))])));
assert.equal(sourceBindings[fontPath], expectedFontSha256, "Font does not match the reviewed original");
assert.equal(sourceBindings[parserPath], expectedParserSha256, "Parser version bytes changed");
const require = createRequire(import.meta.url);
const opentype = require(resolve(root, parserPath));
const bytes = await readFile(resolve(root, fontPath));
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const round = (value) => { const n = Number(value.toFixed(4)); return Object.is(n, -0) ? 0 : n; };
const geometry = [];
for (const target of targets) {
  const path = font.getPath(target.text, 0, 0, 1000, { kerning: true, hinting: false });
  const box = path.getBoundingBox(), width = box.x2 - box.x1, height = box.y2 - box.y1;
  assert.ok(width > 0 && height > 0);
  const x = (value) => round((value - (box.x1 + box.x2) / 2) * target.width / width);
  const y = (value) => round((value - (box.y1 + box.y2) / 2) * target.height / height);
  const commands = path.commands.map((command) => {
    switch (command.type) {
      case "M": case "L": return [command.type, x(command.x), y(command.y)];
      case "Q": return ["Q", x(command.x1), y(command.y1), x(command.x), y(command.y)];
      case "C": return ["C", x(command.x1), y(command.y1), x(command.x2), y(command.y2), x(command.x), y(command.y)];
      case "Z": return ["Z"];
      default: throw Error(`Unsupported font outline command: ${command.type}`);
    }
  });
  geometry.push({ ...target, sourceBounds: box, commands });
}

const header = `/*!\n * Combo Praise Lettering: three fixed game words, derived from Lilita One 1.002.\n * Font copyright (c) 2011 Juan Montoreano (juan@remolacha.biz).\n * SIL Open Font License 1.1; original font, OFL and FONTLOG are archived in\n * art-source/ui/combo-praise-lettering/. This is not a runtime font family.\n */\n// Generated by tools/generate-combo-lettering.mjs. Do not edit coordinates by hand.\n// Original font SHA256: ${expectedFontSha256}\n\n`;
const types = `export type ComboPraiseLetteringTier = "good" | "great" | "excellent";\nexport type ComboLetteringCommand =\n  | readonly ["M" | "L", number, number]\n  | readonly ["Q", number, number, number, number]\n  | readonly ["C", number, number, number, number, number, number]\n  | readonly ["Z"];\nexport interface ComboPraiseLettering {\n  readonly text: string;\n  readonly width: number;\n  readonly height: number;\n  readonly bounds: { readonly x: number; readonly y: number; readonly width: number; readonly height: number };\n  readonly commands: readonly ComboLetteringCommand[];\n}\n\n`;
const data = geometry.map(({ tier, text, width, height, commands }) => `  ${tier}: {\n    text: ${JSON.stringify(text)}, width: ${width}, height: ${height},\n    bounds: { x: ${-width / 2}, y: ${-height / 2}, width: ${width}, height: ${height} },\n    commands: [\n${commands.map((command) => `      ${JSON.stringify(command)},`).join("\n")}\n    ],\n  },`).join("\n");
const helper = `\n/** Leaves one compound path ready for stroke/fill; original contour winding keeps letter holes open. */\nexport function traceComboPraiseLettering(ctx: CanvasRenderingContext2D, tier: ComboPraiseLetteringTier): void {\n  const lettering: ComboPraiseLettering = COMBO_PRAISE_LETTERING[tier];\n  ctx.beginPath();\n  for (const command of lettering.commands) {\n    switch (command[0]) {\n      case "M": ctx.moveTo(command[1], command[2]); break;\n      case "L": ctx.lineTo(command[1], command[2]); break;\n      case "Q": ctx.quadraticCurveTo(command[1], command[2], command[3], command[4]); break;\n      case "C": ctx.bezierCurveTo(command[1], command[2], command[3], command[4], command[5], command[6]); break;\n      case "Z": ctx.closePath(); break;\n    }\n  }\n}\n`;
const code = `${header}${types}export const COMBO_PRAISE_LETTERING = {\n${data}\n} as const satisfies Record<ComboPraiseLetteringTier, ComboPraiseLettering>;\n${helper}`;
const provenance = {
  schemaVersion: 1,
  sourceBindings,
  font: { path: fontPath, sha256: expectedFontSha256, version: font.names.version.en,
    family: font.names.fontFamily.en, copyright: font.names.copyright.en,
    sourceUrl: "https://raw.githubusercontent.com/google/fonts/main/ofl/lilitaone/LilitaOne-Regular.ttf",
    license: { path: `${base}/OFL.txt`, sourceUrl: "https://raw.githubusercontent.com/google/fonts/main/ofl/lilitaone/OFL.txt" },
    fontlog: { path: `${base}/FONTLOG.txt`, sourceUrl: "https://raw.githubusercontent.com/google/fonts/main/ofl/lilitaone/FONTLOG.txt" } },
  parser: { path: parserPath, version: "1.3.4", sha256: expectedParserSha256,
    note: "Build-only parser archived byte-for-byte from the parent-provided distribution; never imported by product code.",
    license: { path: `${base}/tooling/LICENSE.txt`, sourceUrl: "https://raw.githubusercontent.com/opentypejs/opentype.js/1.3.4/LICENSE" } },
  transform: { reference: "QQ20261009-150339.mp4", layout: "independent x/y normalization to centered fixed word bounds",
    kerning: true, hinting: false, coordinateDecimalPlaces: 4, colorAndAnimation: "Applied by comboAnimation.ts; not part of outline data" },
  words: geometry.map(({ tier, text, width, height, sourceBounds, commands }) => ({ tier, text, width, height, sourceBounds,
    commandCount: commands.length, commandSha256: sha256(JSON.stringify(commands)) })),
  output: { path: outputPath, sha256: sha256(code) },
};
const provenanceText = `${JSON.stringify(provenance, null, 2)}\n`;
if (process.argv.includes("--check")) {
  assert.equal(await readFile(resolve(root, outputPath), "utf8"), code, "Runtime outline data is not a deterministic rebuild");
  assert.equal(await readFile(resolve(root, provenancePath), "utf8"), provenanceText, "Outline provenance is stale");
} else {
  await writeFile(resolve(root, outputPath), code);
  await writeFile(resolve(root, provenancePath), provenanceText);
}
console.log(JSON.stringify({ status: "PASS", checkOnly: process.argv.includes("--check"), output: provenance.output,
  words: provenance.words.map(({ tier, width, height, commandCount }) => ({ tier, width, height, commandCount })) }, null, 2));
