#!/usr/bin/env node
throw new Error("Retired label-only admission. Daily schema 2 requires emit-catalog.mjs and verify-runtime.mjs on all 450 exact objects; old PASS reports cannot admit new layouts.");
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const catalogPath = process.argv[2] ?? "deliverables/daily-challenge-formal-20261005/catalog.json";
const proofPath = process.argv[3] ?? "deliverables/daily-challenge-formal-20261006/proof-report.json";
const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
const proof = JSON.parse(await readFile(proofPath, "utf8"));
assert.equal(proof.status, "PASS_INDEPENDENT_LOWER_BOUND_AND_ROUTE");
assert.equal(proof.slotCount, 450);
assert.deepEqual(proof.counts, { PASS: 450 });
const results = new Map(proof.results.map((result) => [result.formalId, result]));
const proofReportSha256 = createHash("sha256").update(await readFile(proofPath)).digest("hex");
let accepted = 0;
for (const stage of catalog.stages) {
  for (const bucket of Object.values(stage.difficulties)) {
    for (const candidate of bucket.candidates) {
      const result = results.get(candidate.formalId);
      assert(result, `missing proof result ${candidate.formalId}`);
      assert.equal(result.status, "PASS", candidate.formalId);
      assert.equal(result.hashBinding?.matched, true, `${candidate.formalId} hash binding`);
      assert.equal(result.lowerBound?.thresholdProven, true, `${candidate.formalId} lower bound`);
      assert.equal(result.route?.replay?.valid, true, `${candidate.formalId} route valid`);
      assert.equal(result.route?.replay?.complete, true, `${candidate.formalId} route complete`);
      candidate.proofStatus = "threshold-proven";
      candidate.proofReport = proofPath.replaceAll("\\", "/");
      candidate.proofReportSha256 = proofReportSha256;
      candidate.proofResultSha256 = createHash("sha256").update(JSON.stringify(result)).digest("hex");
      candidate.proofTargetFloor = result.proofTargetFloor;
      candidate.proofLowerBound = result.lowerBound.composition?.componentFloorSum ?? result.lowerBound.relaxedNonClearingDrags;
      candidate.routeReplayComplete = true;
      accepted += 1;
    }
  }
}
assert.equal(accepted, 450);
catalog.status = "FORMAL_INDEPENDENT_LAYOUTS_PROVEN";
catalog.proofReport = proofPath.replaceAll("\\", "/");
catalog.proofReportSha256 = proofReportSha256;
catalog.notes = [
  "450个槽位均使用独立seam-chambers-v1布局；源图语义与颜色无关几何指纹均已绑定。",
  "每个槽位均完成同一LevelSpec上的validate、authoritative witness fresh replay和checkRevisedRepositionFloor真实下界证明。",
  "D1/D2/D3的证明目标分别为11/21/31次非清除拖动；D3的31严格满足必挪次数大于30。",
  "该目录独立于主线LEVELS、存档与发布包；正式数据已验收但不发布。",
];
await writeFile(catalogPath, `${JSON.stringify(catalog, null, 2)}\n`, "utf8");
const tsData = [
  "// Generated by tools/daily-challenge/accept-formal-proof.mjs; proof-bound formal daily registry.",
  "// This registry is isolated from LEVELS and is not a release/publish action.",
  "export const FORMAL_DAILY_CHALLENGE_SCHEMA_VERSION = 1 as const;",
  `export const FORMAL_DAILY_CHALLENGE_CATALOG = ${JSON.stringify(catalog.stages, null, 2)} as const;`,
  "export type FormalDailyChallengeStage = (typeof FORMAL_DAILY_CHALLENGE_CATALOG)[number];",
  "export type FormalDailyChallengeDifficulty = 1 | 2 | 3;",
  "export const getFormalDailyChallengeStage = (stageKey: string): FormalDailyChallengeStage | undefined => FORMAL_DAILY_CHALLENGE_CATALOG.find((stage) => stage.stageKey === stageKey);",
  "export const getFormalDailyChallengeAssignments = (stageKey: string, difficulty: FormalDailyChallengeDifficulty) => {",
  "  const stage = getFormalDailyChallengeStage(stageKey);",
  "  const bucket = stage?.difficulties[String(difficulty) as keyof typeof stage.difficulties];",
  "  return bucket?.candidates.map((candidate) => ({ id: candidate.formalId, sourceLevelId: candidate.sourceLevelId, variant: candidate.variant, minimumRepositionMoves: candidate.minimumRepositionMoves, sourceDifficulty: candidate.sourceDifficulty, layoutVariant: candidate.layoutVariant, sourceLayoutSha256: candidate.sourceLayoutSha256, layoutSha256: candidate.layoutSha256, layoutDiffersFromSource: candidate.layoutDiffersFromSource, sourceGeometrySha256: candidate.sourceGeometrySha256, geometrySha256: candidate.geometrySha256, geometryDiffersFromSource: candidate.geometryDiffersFromSource, layoutFactory: candidate.layoutFactory, chamberCount: candidate.chamberCount, dailyMechanisms: candidate.dailyMechanisms, proofReport: candidate.proofReport, proofReportSha256: candidate.proofReportSha256, proofResultSha256: candidate.proofResultSha256, proofTargetFloor: candidate.proofTargetFloor, proofLowerBound: candidate.proofLowerBound, routeReplayComplete: candidate.routeReplayComplete, proofStatus: candidate.proofStatus }));",
  "};",
  "",
].join("\n");
await writeFile("src/core/formalDailyChallengeData.ts", tsData, "utf8");
console.log(`FORMAL_ACCEPTED ${accepted} slots; proof sha256=${proofReportSha256}`);
