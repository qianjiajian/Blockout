function languageFor(value: unknown): PrivacyLanguage {
  if (typeof value !== "string") return "en";
  const locale = value.toLowerCase().replace(/_/g, "-");
  if (/^zh-(tw|hk|mo|hant)(-|$)/.test(locale)) return "zh-TW";
  return /^zh($|-)/.test(locale) ? "zh-CN" : "en";
}

function record(value: unknown): Record<string, unknown> | undefined {
  return value !== null && typeof value === "object" ? value as Record<string, unknown> : undefined;
}

/** The overlay reads presentation snapshots only. It does not invoke any game
 * action, touch storage, or alter rewards/progression while showing a notice. */
export function installGooglePlayPrivacy(canvas: HTMLCanvasElement, readState: () => GooglePlayPrivacyState, native?: {
  isPrivacyOptionsAvailable(): boolean;
  showPrivacyOptions(): Promise<boolean>;
  reviews?: { readonly pending: boolean; sync(ready: () => boolean): Promise<void>; openStore(): Promise<boolean>; onPending(listener: () => void): () => void };
}): () => void {
  const entry = document.createElement("button");
  entry.id = "google-play-privacy-button";
  entry.className = "gp-privacy-entry";
  entry.type = "button";
  entry.hidden = true;
  entry.setAttribute("aria-haspopup", "dialog");
  entry.setAttribute("aria-controls", "google-play-privacy-dialog");
  entry.setAttribute("aria-expanded", "false");

  const overlay = document.createElement("div");
  overlay.id = "google-play-privacy-overlay";
  overlay.className = "gp-privacy-overlay";
  overlay.hidden = true;
  const dialog = document.createElement("section");
  dialog.id = "google-play-privacy-dialog";
  dialog.className = "gp-privacy-dialog";
  dialog.setAttribute("role", "dialog");
  dialog.setAttribute("aria-modal", "true");
  dialog.setAttribute("aria-labelledby", "google-play-privacy-title");
  const header = document.createElement("header");
  header.className = "gp-privacy-header";
  const title = document.createElement("h1");
  title.id = "google-play-privacy-title";
  const close = document.createElement("button");
  close.id = "google-play-privacy-close";
  close.type = "button";
  close.className = "gp-privacy-close";
  const content = document.createElement("div");
  content.className = "gp-privacy-content";
  content.tabIndex = 0;
  header.append(title, close);
  dialog.append(header, content);
  overlay.append(dialog);
  const rate = document.createElement("button");
  rate.id = "google-play-review-button";
  rate.type = "button";
  rate.className = "gp-privacy-entry";
  rate.hidden = true;
  document.body.append(entry, rate, overlay);

  let disposed = false;
  let pageHidden = document.hidden;
  let open = false;
  let settingsVisible = false;
  let currentLanguage: PrivacyLanguage | undefined;
  let syncTimer: number | undefined;
  let interactionTimer: number | undefined;
  let previousFocus: HTMLElement | null = null;
  let previousTouchAction = "";
  let previousCanvasAriaHidden: string | null = null;
  const historyMarker = `block-out-privacy-${Date.now()}`;
  let historyEntryOwned = false;
  let historyRestorePending = false;
  let previousHistoryUrl = "";
  let previousHistoryState: unknown;
  let choicesButton: HTMLButtonElement | undefined;
  let choicesMessage: HTMLParagraphElement | undefined;
  let choicesPending = false;
  const removeListeners: Array<() => void> = [];
  const listen = (target: EventTarget, type: string, listener: EventListener, capture = false): void => {
    target.addEventListener(type, listener, { capture, passive: false });
    removeListeners.push(() => target.removeEventListener(type, listener, capture));
  };

  function setCopy(language: PrivacyLanguage): void {
    if (currentLanguage === language) return;
    currentLanguage = language;
    rate.textContent = language === "zh-CN" ? "Google Play 评价" : language === "zh-TW" ? "Google Play 評價" : "Rate us on Google Play";
    const copy = COPY[language];
    entry.textContent = copy.button;
    entry.lang = language;
    dialog.lang = language;
    title.textContent = copy.title;
    close.textContent = copy.close;
    content.setAttribute("aria-label", copy.title);
    while (content.firstChild) content.removeChild(content.firstChild);
    const introduction = document.createElement("p");
    introduction.textContent = copy.introduction;
    content.append(introduction);
    for (const [heading, description] of copy.sections) {
      const section = document.createElement("section");
      const label = document.createElement("h2");
      const paragraph = document.createElement("p");
      label.textContent = heading;
      paragraph.textContent = description;
      section.append(label, paragraph);
      content.append(section);
    }
    choicesButton = document.createElement("button");
    choicesButton.id = "google-play-ad-privacy-options";
    choicesButton.className = "gp-privacy-choices";
    choicesButton.type = "button";
    choicesButton.textContent = copy.choices;
    choicesButton.hidden = !native?.isPrivacyOptionsAvailable();
    choicesMessage = document.createElement("p");
    choicesMessage.id = "google-play-ad-privacy-message";
    choicesMessage.setAttribute("role", "status");
    choicesMessage.hidden = true;
    choicesButton.addEventListener("click", async event => {
      event.preventDefault(); event.stopPropagation();
      if (disposed || choicesPending || !native?.isPrivacyOptionsAvailable()) return;
      choicesPending = true;
      choicesButton!.disabled = true;
      choicesMessage!.hidden = true;
      let success = false;
      try { success = await native.showPrivacyOptions(); } catch { /* keep the game and notice usable */ }
      choicesPending = false;
      if (disposed) return;
      choicesButton!.disabled = false;
      choicesButton!.hidden = !native.isPrivacyOptionsAvailable();
      choicesMessage!.textContent = COPY[currentLanguage ?? "en"].choicesFailed;
      choicesMessage!.hidden = success;
    });
    content.append(choicesButton, choicesMessage);
    const contact = document.createElement("section");
    contact.className = "gp-privacy-contact";
    const contactHeading = document.createElement("h2");
    contactHeading.textContent = copy.contact.heading;
    const operator = document.createElement("p");
    const operatorLabel = document.createElement("strong");
    operatorLabel.textContent = copy.contact.operator;
    const operatorName = document.createElement("span");
    operatorName.id = "google-play-privacy-operator";
    operatorName.textContent = OPERATOR_NAME;
    operator.append(operatorLabel, operatorName);
    const email = document.createElement("p");
    const emailLabel = document.createElement("strong");
    emailLabel.textContent = copy.contact.email;
    const emailLink = document.createElement("a");
    emailLink.id = "google-play-privacy-email";
    emailLink.href = `mailto:${CONTACT_EMAIL}`;
    emailLink.textContent = CONTACT_EMAIL;
    email.append(emailLabel, emailLink);
    const policy = document.createElement("p");
    const policyLink = document.createElement("a");
    policyLink.id = "google-play-privacy-policy";
    policyLink.href = PRIVACY_POLICY_URL;
    policyLink.rel = "noreferrer";
    const policyLabel = document.createElement("span");
    policyLabel.textContent = copy.contact.policy;
    const policyAddress = document.createElement("span");
    policyAddress.className = "gp-privacy-link-address";
    policyAddress.textContent = PRIVACY_POLICY_URL;
    policyLink.append(policyLabel, policyAddress);
    policy.append(policyLink);
    const externalNotice = document.createElement("p");
    externalNotice.textContent = copy.contact.externalNotice;
    contact.append(contactHeading, operator, email, policy, externalNotice);
    content.append(contact);
  }

  function ownsCurrentHistoryEntry(): boolean {
    try { return record(window.history.state)?.blockOutPrivacy === historyMarker; }
    catch { return false; }
  }

  function removeHistoryEntry(navigateBack: boolean): void {
    if (!historyEntryOwned && !historyRestorePending) return;
    historyEntryOwned = false;
    if (!ownsCurrentHistoryEntry()) { historyRestorePending = false; return; }
    try {
      if (navigateBack) {
        historyRestorePending = true;
        window.history.back();
      } else {
        window.history.replaceState(previousHistoryState, "", previousHistoryUrl);
        historyRestorePending = false;
      }
    } catch {
      historyRestorePending = false;
      try { window.history.replaceState(previousHistoryState, "", previousHistoryUrl); } catch { /* notice still closes */ }
    }
  }

  function closeNotice(restoreFocus = true, restoreHistory = true): void {
    if (!open) return;
    open = false;
    overlay.hidden = true;
    entry.setAttribute("aria-expanded", "false");
    document.body.style.touchAction = previousTouchAction;
    if (previousCanvasAriaHidden === null) canvas.removeAttribute("aria-hidden");
    else canvas.setAttribute("aria-hidden", previousCanvasAriaHidden);
    if (restoreFocus && !pageHidden) {
      const target = settingsVisible ? entry : previousFocus;
      if (target?.isConnected) target.focus();
    }
    previousFocus = null;
    if (restoreHistory) removeHistoryEntry(true);
  }

  function placeEntry(transform: GooglePlayPrivacyState["viewportTransform"]): boolean {
    const scale = Number(transform.scale);
    const offsetX = Number(transform.offsetX);
    const offsetY = Number(transform.offsetY);
    if (!(scale > 0) || !Number.isFinite(scale) || !Number.isFinite(offsetX) || !Number.isFinite(offsetY)) return false;
    const bounds = canvas.getBoundingClientRect();
    if (bounds.width <= 0 || bounds.height <= 0) return false;
    const artScale = 496 / 720;
    const artOffsetY = (1078 - 1584 * artScale) / 2;
    const rect = PAUSE_SETTINGS_LAYOUT.settingsClearButton;
    const width = rect.width * artScale * scale;
    const height = rect.height * artScale * scale;
    Object.assign(entry.style, {
      left: `${bounds.left + offsetX + rect.x * artScale * scale}px`,
      top: `${bounds.top + offsetY + (rect.y * artScale + artOffsetY) * scale}px`,
      width: `${width}px`, height: `${height}px`, fontSize: `${Math.max(11, width * 0.12)}px`,
      borderRadius: `${height * 0.22}px`,
    });
    Object.assign(rate.style, {
      left: `${bounds.left + offsetX + 160 * artScale * scale}px`,
      top: `${bounds.top + offsetY + (925 * artScale + artOffsetY) * scale}px`,
      width: `${400 * artScale * scale}px`, height: `${72 * artScale * scale}px`,
      fontSize: `${Math.max(11, 27 * artScale * scale)}px`, borderRadius: `${14 * artScale * scale}px`,
    });
    return true;
  }

  function clearTimers(): void {
    if (syncTimer !== undefined) window.clearTimeout(syncTimer);
    if (interactionTimer !== undefined) window.clearTimeout(interactionTimer);
    syncTimer = undefined;
    interactionTimer = undefined;
  }

  function sync(): void {
    if (syncTimer !== undefined) window.clearTimeout(syncTimer);
    syncTimer = undefined;
    if (disposed || pageHidden || document.hidden) return;
    const state = readState();
    settingsVisible = state.screen === "settings";
    const transform = state.viewportTransform;
    setCopy(languageFor(state.settings.language));
    if (choicesButton) choicesButton.hidden = !native?.isPrivacyOptionsAvailable();
    entry.hidden = !settingsVisible || !transform || !placeEntry(transform);
    rate.hidden = entry.hidden || !native?.reviews;
    if (!settingsVisible) closeNotice(false);
    if (!open && native?.reviews?.pending) void native.reviews.sync(() => !disposed && !pageHidden && !document.hidden && !open && readState().reviewReady === true);
    // Only tiny presentation snapshots are read here. Settings polls for
    // language/geometry changes; gameplay refreshes after finished interactions.
    if (settingsVisible || (native?.reviews?.pending && ["home", "win"].includes(state.screen))) syncTimer = window.setTimeout(sync, 250);
  }

  function scheduleInteractionSync(): void {
    if (disposed || pageHidden || document.hidden) return;
    if (interactionTimer !== undefined) window.clearTimeout(interactionTimer);
    interactionTimer = window.setTimeout(() => {
      interactionTimer = undefined;
      sync();
    }, 0);
  }

  function openNotice(event: Event): void {
    event.preventDefault();
    event.stopPropagation();
    sync();
    if (disposed || pageHidden || entry.hidden || open || historyRestorePending) return;
    previousFocus = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    previousTouchAction = document.body.style.touchAction;
    previousCanvasAriaHidden = canvas.getAttribute("aria-hidden");
    // The shared page disables touch scrolling for the canvas. Temporarily
    // allow vertical panning so the independent notice can actually scroll.
    document.body.style.touchAction = "pan-y";
    canvas.setAttribute("aria-hidden", "true");
    open = true;
    try {
      previousHistoryUrl = window.location.href;
      previousHistoryState = window.history.state;
      window.history.pushState({ blockOutPrivacy: historyMarker }, "", `${previousHistoryUrl.split("#")[0]}#privacy`);
      historyEntryOwned = true;
    } catch { historyEntryOwned = false; }
    overlay.hidden = false;
    entry.setAttribute("aria-expanded", "true");
    content.scrollTop = 0;
    content.focus();
  }

  const stopPropagation = (event: Event): void => event.stopPropagation();
  const blockBackground = (event: Event): void => {
    if (!open) return;
    if (!(event.target instanceof Node) || !dialog.contains(event.target)) {
      if (event.cancelable) event.preventDefault();
      event.stopImmediatePropagation();
    }
  };
  const onKey = (event: Event): void => {
    if (!open) return;
    const key = event as KeyboardEvent;
    key.stopImmediatePropagation();
    if (key.key === "Escape") {
      key.preventDefault();
      closeNotice();
    } else if (key.key === "Tab") {
      const focused = document.activeElement;
      const focusable = Array.from(dialog.querySelectorAll<HTMLElement>('button:not([disabled]), a[href], [tabindex]:not([tabindex="-1"])'))
        .filter(element => !element.hidden && element.getClientRects().length > 0);
      const first = focusable[0] ?? close;
      const last = focusable[focusable.length - 1] ?? content;
      if ((key.shiftKey && focused === first) || (!key.shiftKey && focused === last) || !dialog.contains(focused)) {
        key.preventDefault();
        (key.shiftKey ? last : first).focus();
      }
    }
  };
  let closePointer: { id: number; x: number; y: number } | undefined;
  listen(close, "pointerdown", (event) => {
    const pointer = event as PointerEvent;
    if (pointer.button === 0) closePointer = { id: pointer.pointerId, x: pointer.clientX, y: pointer.clientY };
  });
  listen(close, "pointercancel", () => { closePointer = undefined; });
  listen(close, "pointerup", (event) => {
    const pointer = event as PointerEvent;
    const started = closePointer;
    closePointer = undefined;
    if (!started || started.id !== pointer.pointerId || !open) return;
    const bounds = close.getBoundingClientRect();
    if (Math.abs(pointer.clientX - started.x) > 10 || Math.abs(pointer.clientY - started.y) > 10
      || pointer.clientX < bounds.left || pointer.clientX > bounds.right
      || pointer.clientY < bounds.top || pointer.clientY > bounds.bottom) return;
    // Mobile browsers may suppress the compatibility click just after a
    // scrolling gesture. A completed tap should still close on its first try.
    pointer.preventDefault();
    pointer.stopPropagation();
    closeNotice();
  });
  listen(rate, "click", async (event) => {
    event.preventDefault(); event.stopPropagation();
    if (rate.disabled || rate.hidden || open || disposed || pageHidden || readState().screen !== "settings") return;
    rate.disabled = true;
    try {
      const opened = await native?.reviews?.openStore();
      if (!opened && !disposed) rate.textContent = currentLanguage === "zh-CN" ? "暂时无法打开，请稍后重试" : "Unavailable — please try again";
    } finally { rate.disabled = false; }
  });
  if (native?.reviews) removeListeners.push(native.reviews.onPending(scheduleInteractionSync));
  listen(entry, "click", openNotice);
  listen(close, "click", (event) => { event.preventDefault(); event.stopPropagation(); closeNotice(); });
  for (const type of ["pointerdown", "pointerup", "pointermove", "pointercancel", "click", "touchstart", "touchend", "touchmove", "mousedown", "mouseup", "wheel"]) {
    listen(document, type, blockBackground, true);
    listen(overlay, type, stopPropagation);
    listen(entry, type, stopPropagation);
    listen(rate, type, stopPropagation);
  }
  listen(document, "keydown", onKey, true);
  listen(document, "focusin", () => {
    if (open && !dialog.contains(document.activeElement)) content.focus();
  });
  listen(document, "pointerup", scheduleInteractionSync);
  listen(document, "pointercancel", scheduleInteractionSync);
  listen(window, "popstate", () => {
    historyRestorePending = false;
    historyEntryOwned = false;
    closeNotice(true, false);
    // Forward navigation must not leave a stale notice URL with no dialog.
    if (ownsCurrentHistoryEntry()) {
      try { window.history.replaceState(previousHistoryState, "", previousHistoryUrl); } catch { /* local URL only */ }
    }
  });
  listen(window, "resize", scheduleInteractionSync);
  listen(document, "visibilitychange", () => {
    pageHidden = document.hidden;
    clearTimers();
    if (!pageHidden) sync();
  });
  listen(window, "pagehide", (event) => {
    if (!(event as PageTransitionEvent).persisted) dispose();
    else { pageHidden = true; clearTimers(); }
  });
  listen(window, "pageshow", () => { pageHidden = document.hidden; if (!pageHidden) sync(); });

  function dispose(): void {
    if (disposed) return;
    disposed = true;
    clearTimers();
    closeNotice(false, false);
    removeHistoryEntry(false);
    removeListeners.forEach(remove => remove());
    entry.remove();
    rate.remove();
    overlay.remove();
  }

  setCopy("en");
  sync();
  return dispose;
}
