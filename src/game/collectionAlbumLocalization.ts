export const collectionAlbumDictionary = (
  language: GameLanguage | string | null | undefined,
): CollectionAlbumDictionary => {
  if (
    typeof language === "string"
    && Object.prototype.hasOwnProperty.call(COLLECTION_ALBUM_TRANSLATIONS, language)
  ) {
    return COLLECTION_ALBUM_TRANSLATIONS[language as GameLanguage];
  }
  return ENGLISH_COLLECTION_ALBUM;
};

/** Replaces named values while keeping omitted placeholders visible for QA. */
export const collectionAlbumText = (
  language: GameLanguage | string | null | undefined,
  key: CollectionAlbumTextKey,
  params: CollectionAlbumTextParams = {},
): string => collectionAlbumDictionary(language)[key].replace(
  /\{([A-Za-z][A-Za-z0-9_]*)\}/g,
  (placeholder, name: string) => {
    const value = params[name as CollectionAlbumPlaceholder];
    return value === undefined ? placeholder : String(value);
  },
);
