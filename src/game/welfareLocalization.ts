export function welfareText(language: string, key: WelfareTextKey,
  values: Readonly<Record<string, string | number>> = {}): string {
  const messages = Object.prototype.hasOwnProperty.call(WELFARE_TEXT, language)
    ? WELFARE_TEXT[language as GameLanguage] : EN;
  return messages[key].replace(/\{(\w+)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token);
}
