import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {build} from 'esbuild';
import {digest} from '../../revised-preview-validation-v160.mjs';
import {verifyRulesLock} from '../../verify-rules-lock.mjs';

const root='deliverables/remake31-200-v145-20260924/batches/lv051-060';
const proofRoot=`${root}/root58`;
const candidate=process.argv[2]??`${root}/rebuild58/enriched-1790263144600.json`;
const prior=process.argv[3]??`${proofRoot}/continued-proof-179026-resume.json`;
const output=process.argv[4]??`${proofRoot}/continued-proof-179026-resume-v151.json`;
const lock=verifyRulesLock();
if(!lock.ok)throw new Error(`rules lock must pass: ${lock.errors.join('; ')}`);
if(lock.activeVersion!=='1.51.0')throw new Error(`expected active v1.51.0, got ${lock.activeVersion}`);
const manifest=JSON.parse(fs.readFileSync('docs/rules/manifest.json','utf8'));
const activeDoc=manifest.versions.find(v=>v.version===lock.activeVersion)?.document;
if(!activeDoc)throw new Error('active rule document missing');
const d=JSON.parse(fs.readFileSync(candidate));
if(d.level.id!==58)throw new Error('candidate is not level 58');
const cli=path.resolve('tools/campaign-v145/lv051-060/continue58-terminal-cli-v151.mjs');
const compiled=await build({stdin:{resolveDir:process.cwd(),contents:"export {PuzzleModel,validateLevel} from './src/core/PuzzleModel.ts';export {replayRevisedRoute} from './src/core/revisedLevelSearch.ts';"},bundle:true,write:false,metafile:true,platform:'node',format:'esm',logLevel:'silent'});
const meta=await build({entryPoints:[cli],bundle:true,write:false,metafile:true,platform:'node',format:'esm',packages:'external',logLevel:'silent'});
const refs=[...new Set([...Object.keys(compiled.metafile.inputs),...Object.keys(meta.metafile.inputs),candidate,d.sourceReview,'docs/rules/manifest.json',activeDoc,'tests/campaign-v145/lv051-060/terminal-normalized-floor58-v147.test.mjs','tests/campaign-v145/lv051-060/continuable-terminal58-v147.test.mjs'].filter(p=>p!=='<stdin>'))];
const bindings=Object.fromEntries(refs.map(p=>[p,digest(fs.readFileSync(p))]));
const fingerprint=digest({bindings,coreBundleSha256:digest(compiled.outputFiles[0].text)});
const old=JSON.parse(fs.readFileSync(prior));
if(old.levelSha256!==digest(d.level))throw new Error('prior level hash does not match candidate');
if(old.routeSha256!==digest(d.drags))throw new Error('prior route hash does not match candidate; use the original 42-drag witness');
if(old.proof?.status!=='unknown')throw new Error('prior proof is not UNKNOWN');
if((old.drift??[]).length)throw new Error('prior report has drift');
const frontierName='terminal-frontier-1790299004912.bin';
const frontier=path.join(proofRoot,frontierName);
if(!fs.existsSync(frontier))throw new Error(`missing checkpoint ${frontier}`);
const stat=fs.statSync(frontier);
if(stat.size<=2_000_000_000)throw new Error(`checkpoint is unexpectedly small: ${stat.size}`);
const hash=crypto.createHash('sha256');
await new Promise((resolve,reject)=>{const stream=fs.createReadStream(frontier);stream.on('data',chunk=>hash.update(chunk));stream.on('error',reject);stream.on('end',resolve);});
const checkpoint={file:frontier,sha256:hash.digest('hex'),bytes:stat.size};
const out={...old,candidate,fingerprint,bindings,ruleVersion:lock.activeVersion,checkedAt:new Date().toISOString(),checkpoint,proof:{...old.proof,termination:'checkpoint-written-resume-ready'},priorProof:old.priorProof??null};
fs.writeFileSync(output,JSON.stringify(out,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({output,ruleVersion:lock.activeVersion,candidate,fingerprint,checkpoint}));
