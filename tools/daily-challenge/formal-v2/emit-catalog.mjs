import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { loadRuntime, levelSha256, BANDS } from './contract.mjs';
import { expectedDailySlots, catalogProgress } from './catalog-progress.mjs';
import { independentPartitionSha256 } from './geometry.mjs';
import { verifyRulesLock } from '../../verify-rules-lock.mjs';

export function requireCompleteCatalog(progress) {
  if(progress.scope!==450 || progress.rows?.length!==450)throw Error('A complete 450-slot catalogue is required');
  if(progress.rejectedIndex?.length || progress.geometryDuplicates?.length)throw Error('Rejected receipts or duplicate layouts');
  const invalid=progress.rows.filter(row=>row.status!=='SPATIAL_VERIFIED_AWAITING_POINTER_TIME');
  if(invalid.length)throw Error(`${invalid.length} slots lack current, same-object spatial certification`);
  if(new Set(progress.rows.map(row=>row.formalId)).size!==450)throw Error('Duplicate or missing formal ids');
}

export function catalogModule(stages, revision) {
  // The entire certified object is emitted, never a recipe that can silently
  // derive a different board. Proof routes remain in offline evidence.
  return `// Generated by tools/daily-challenge/formal-v2/emit-catalog.mjs.\n`+
`// Full objects and fresh lower/upper bounds are bound to the same SHA-256.\n`+
`import type { Difficulty, LevelSpec } from "./types";\n`+
`import { clonePlainData } from "./clonePlainData";\n`+
`export const FORMAL_DAILY_CHALLENGE_SCHEMA_VERSION = 2 as const;\n`+
`export const FORMAL_DAILY_CHALLENGE_REVISION = ${JSON.stringify(revision)};\n`+
`export type FormalDailyChallengeDifficulty = 1 | 2 | 3;\n`+
`export interface FormalDailyChallengeCandidate {\n`+
`  formalId: string; slot: number; sourceLevelId: number; variant: number;\n`+
`  sourceDifficulty: Difficulty; dailyDifficulty: string; timeSeconds: number;\n`+
`  minimumRepositionMoves: number; verifiedSolutionRepositionMoves: number;\n`+
`  proofTargetFloor: number; proofLowerBound: number; proofUpperBound: number;\n`+
`  proofStatus: "same-object-verified-v2"; proofSchemaVersion: 2; routeReplayComplete: true;\n`+
`  layoutFactory: "explicit-certified-v2"; layoutSha256: string; sourceLayoutSha256: string;\n`+
`  layoutDiffersFromSource: true; geometrySha256: string; sourceGeometrySha256: string; geometryDiffersFromSource: true;\n`+
`  dailyMechanisms: string[]; sourceMechanisms: string[];\n`+
`  proofReport: string; proofReportSha256: string; routeSha256: string; toolchainSha256: string;\n`+
`  level: LevelSpec;\n`+
`}\n`+
`export interface FormalDailyChallengeStage {\n`+
`  stageKey: string; unlockLevel: number; newestMechanism: string; unlockedMechanisms: string[];\n`+
`  difficulties: Record<FormalDailyChallengeDifficulty, { label: string; candidates: FormalDailyChallengeCandidate[]; uniqueSourceCount: number; repeatedSourceVariants: number }>;\n`+
`}\n`+
`function freezeTree<T>(value: T): T {\n`+
`  if(value && typeof value === "object" && !Object.isFrozen(value)) {\n`+
`    for(const child of Object.values(value)) freezeTree(child); Object.freeze(value);\n`+
`  } return value;\n`+
`}\n`+
`export const FORMAL_DAILY_CHALLENGE_CATALOG: readonly FormalDailyChallengeStage[] = freezeTree(${JSON.stringify(stages,null,2)});\n`+
`const candidates = new Map(FORMAL_DAILY_CHALLENGE_CATALOG.flatMap(stage => [1,2,3].flatMap(difficulty =>\n`+
`  stage.difficulties[difficulty as FormalDailyChallengeDifficulty].candidates.map(candidate => [candidate.formalId,candidate] as const))));\n`+
`export const getFormalDailyChallengeStage = (stageKey: string): FormalDailyChallengeStage | undefined => FORMAL_DAILY_CHALLENGE_CATALOG.find(stage => stage.stageKey === stageKey);\n`+
`export const getFormalDailyChallengeCandidate = (formalId: string): FormalDailyChallengeCandidate | undefined => candidates.get(formalId);\n`+
`export const getFormalDailyChallengeLevel = (formalId: string): LevelSpec | undefined => {\n`+
`  const candidate = candidates.get(formalId); return candidate ? clonePlainData(candidate.level) : undefined;\n`+
`};\n`+
`export const getFormalDailyChallengeAssignments = (stageKey: string, difficulty: FormalDailyChallengeDifficulty) =>\n`+
`  getFormalDailyChallengeStage(stageKey)?.difficulties[difficulty].candidates.map(({ level: _level, formalId, ...metadata }) =>\n`+
`    ({ ...metadata, id: formalId, catalogRevision: FORMAL_DAILY_CHALLENGE_REVISION }));\n`;
}

export async function emitCatalog(indexFile, output) {
  const lock=verifyRulesLock();if(!lock.ok)throw Error('Rules lock failed');
  const runtime=await loadRuntime(),index=JSON.parse(await fs.readFile(indexFile,'utf8'));
  if(!Array.isArray(index.files))throw Error('An explicit selected receipt list is required');
  const progress=await catalogProgress(runtime,index.files);requireCompleteCatalog(progress);
  const expected=expectedDailySlots(runtime.MECHANISM_GUIDE),byId=new Map();
  for(const row of progress.rows){
    const bytes=await fs.readFile(row.file),receipt=JSON.parse(bytes.toString('utf8'));
    byId.set(row.formalId,{receipt,file:row.file,hash:createHash('sha256').update(bytes).digest('hex')});
  }
  const labels={1:'难',2:'超难',3:'超超难'};
  const stages=runtime.MECHANISM_GUIDE.map(mechanism=>{
    const stageKey=`mechanisms-${mechanism.id}-${mechanism.unlockLevel}`;
    const difficulties=Object.fromEntries([1,2,3].map(difficulty=>{
      const candidates=expected.filter(slot=>slot.stageKey===stageKey&&slot.difficulty===difficulty).map(slot=>{
        const {receipt:r,file,hash}=byId.get(slot.formalId),source=runtime.LEVELS.find(l=>l.id===r.sourceLevelId);
        return {formalId:slot.formalId,slot:slot.slot,sourceLevelId:r.sourceLevelId,variant:slot.slot-1,
          sourceDifficulty:source.difficulty,dailyDifficulty:labels[difficulty],timeSeconds:r.level.timeSeconds,
          minimumRepositionMoves:r.L,verifiedSolutionRepositionMoves:r.U,
          proofTargetFloor:BANDS[difficulty].lower,proofLowerBound:r.L,proofUpperBound:r.U,
          proofStatus:'same-object-verified-v2',proofSchemaVersion:2,routeReplayComplete:true,
          layoutFactory:'explicit-certified-v2',layoutSha256:r.levelSha256,sourceLayoutSha256:r.sourceLevelSha256,
          layoutDiffersFromSource:true,geometrySha256:independentPartitionSha256(r.level),sourceGeometrySha256:independentPartitionSha256(source),geometryDiffersFromSource:true,
          dailyMechanisms:runtime.mechanismsUsedByDailyLevel(r.level),sourceMechanisms:runtime.mechanismsUsedByDailyLevel(source),
          proofReport:file,proofReportSha256:hash,routeSha256:r.routeSha256,toolchainSha256:r.toolchainSha256,level:r.level};
      });
      const uniqueSourceCount=new Set(candidates.map(c=>c.sourceLevelId)).size;
      return [difficulty,{label:labels[difficulty],candidates,uniqueSourceCount,repeatedSourceVariants:10-uniqueSourceCount}];
    }));
    return{stageKey,unlockLevel:mechanism.unlockLevel,newestMechanism:mechanism.id,
      unlockedMechanisms:runtime.MECHANISM_GUIDE.filter(m=>m.unlockLevel<=mechanism.unlockLevel).map(m=>m.id),difficulties};
  });
  const revision=levelSha256(stages),module=catalogModule(stages,revision);
  await fs.mkdir(output,{recursive:false});
  await fs.writeFile(`${output}/formalDailyChallengeData.ts`,module,{flag:'wx'});
  await fs.writeFile(`${output}/catalog.json`,JSON.stringify({schemaVersion:2,revision,stages},null,2)+'\n',{flag:'wx'});
  const manifest={schemaVersion:2,scope:450,revision,ruleVersion:lock.activeVersion,indexFile,
    status:'FULL_CATALOG_STAGED_AWAITING_RUNTIME_POINTER',formalReady:false,productionChanged:false,
    moduleSha256:createHash('sha256').update(module).digest('hex'),files:index.files,progress};
  await fs.writeFile(`${output}/manifest.json`,JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
  return manifest;
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
  const [indexFile,output]=process.argv.slice(2);if(!indexFile||!output)throw Error('Usage: emit-catalog.mjs selected-index.json new-output-directory');
  const manifest=await emitCatalog(indexFile,output);console.log(JSON.stringify({output,scope:manifest.scope,status:manifest.status,revision:manifest.revision}));
}
